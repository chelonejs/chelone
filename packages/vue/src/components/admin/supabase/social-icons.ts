/**
 * Brand marks for the provider buttons, drawn 20 by 20 and hidden from
 * assistive tech: the button's label names the provider. The Vue twin of
 * `@chelone/react`'s `social-icons.tsx`, as functional components built with
 * `h` because `@chelone/vue` has no icon library.
 *
 * Filled marks follow the Simple Icons glyphs (CC0). Marks drawn here from
 * plain shapes (Azure, Keycloak, Notion, WorkOS) are stylised, not the
 * official artwork.
 */

import { type FunctionalComponent, h, type VNode } from "vue";

type PathSpec = { d: string; fill?: string; outline?: boolean };

/** A shared `<svg>` shell around `paths`; `fill: "none"` for multi-colour marks. */
function mark(paths: PathSpec[], fill = "currentColor"): FunctionalComponent {
  const icon: FunctionalComponent = (_props, { attrs }) =>
    h(
      "svg",
      {
        xmlns: "http://www.w3.org/2000/svg",
        viewBox: "0 0 24 24",
        width: 20,
        height: 20,
        "aria-hidden": "true",
        focusable: "false",
        fill,
        ...attrs,
      },
      paths.map(
        ({ d, fill: pathFill, outline }): VNode =>
          h("path", {
            d,
            ...(pathFill ? { fill: pathFill } : {}),
            ...(outline
              ? {
                  fill: "none",
                  stroke: "currentColor",
                  "stroke-width": 2,
                  "stroke-linecap": "round",
                  "stroke-linejoin": "round",
                }
              : {}),
          }),
      ),
    );
  return icon;
}


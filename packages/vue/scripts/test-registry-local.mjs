#!/usr/bin/env node

// Local linked-consumer check for the built Vue registry items. The generate
// and build gates read file lists, not file content, so a broken import in a
// shipped .vue file would pass them. This copies each representative item and
// its @chelone registry dependencies from dist/r into a scratch consumer at
// their src/ paths and runs vue-tsc over the copies. Vue twin of
// packages/react/scripts/test-registry-local.mjs.
//
// Run: pnpm registry:build && pnpm registry:test-local

import { execFileSync } from "node:child_process";
import {
  mkdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(scriptDir, "..");
const distDir = join(pkgRoot, "dist", "r");
const scratchDir = join(pkgRoot, "temp-local-e2e");

// `logout` imports ../layout/icons and `spinner` wraps ui-spinner, so both
// need a sibling item that only the dependency closure supplies.
const REPRESENTATIVE_ITEMS = [
  "admin",
  "text-input",
  "text-field",
  "data-table",
  "edit",
  "app-sidebar",
  "logout",
  "spinner",
];

// Keeps module-resolution errors reported against a copied .vue or .ts file:
// TS2307 module not found, TS2305 no exported member, and the three codes a
// `.vue` import reports instead. Every `.vue` module has a default export, so a
// missing named import comes back as TS2614 (or TS2724 when a close name
// exists) and a missing default as TS1192. The tsconfig pins rootDir to src, so
// copied files are always reported with a `src/` prefix.
const SOURCE_DIAGNOSTIC = /^src\/.+\.(vue|ts)\(\d+,\d+\): error TS\d+:/;

export const filterResolutionErrors = (compilerOutput) =>
  compilerOutput
    .split("\n")
    .filter((line) =>
      /^src\/.+\.(vue|ts)\(\d+,\d+\): error TS(2307|2305|2614|2724|1192):/.test(
        line,
      ),
    );

// vue-tsc exits non-zero on ordinary type noise, so a non-zero exit alone is not
// a failure. A compiler that never spawned, or that failed without reporting one
// source diagnostic (a bad tsconfig, no inputs), checked nothing and must not
// read as a pass.
export const compilerRunFailure = ({ code, status, output }) => {
  if (code || status === null || status === undefined) {
    return `vue-tsc did not run (${code ?? "no exit status"})`;
  }
  if (status !== 0 && !output.split("\n").some((l) => SOURCE_DIAGNOSTIC.test(l))) {
    return `vue-tsc exited ${status} with no diagnostics on copied files:\n${output}`;
  }
  return null;
};

const loadItem = (name) => {
  try {
    return JSON.parse(readFileSync(join(distDir, `${name}.json`), "utf8"));
  } catch {
    throw new Error(
      `Missing dist item "${name}.json", run "pnpm registry:build" first.`,
    );
  }
};

// Bare (non-@chelone) registryDependencies are stock shadcn-vue primitives a
// consumer already has, so only @chelone ones are followed.
const collectTransitive = (rootNames) => {
  const items = new Map();
  const stack = [...rootNames];
  while (stack.length) {
    const name = stack.pop();
    if (items.has(name)) continue;
    const item = loadItem(name);
    items.set(name, item);
    for (const dep of item.registryDependencies ?? []) {
      if (!dep.startsWith("@chelone/")) continue;
      const target = dep.slice("@chelone/".length);
      if (!items.has(target)) stack.push(target);
    }
  }
  return items;
};

const main = () => {
  rmSync(scratchDir, { recursive: true, force: true });
  mkdirSync(join(scratchDir, "src"), { recursive: true });

  const items = collectTransitive(REPRESENTATIVE_ITEMS);

  const writtenPaths = new Set();
  for (const item of items.values()) {
    for (const file of item.files ?? []) {
      if (typeof file.content !== "string") continue;
      const dest = join(scratchDir, file.path);
      mkdirSync(dirname(dest), { recursive: true });
      writeFileSync(dest, file.content);
      writtenPaths.add(file.path);
    }
  }

  // The engine packages are opaque: their internals are not under test, only
  // whether each import of them resolves. There is deliberately no `*.vue`
  // module shim, which would hide a missing .vue file, and no `@/components/ui`
  // stub, which would hide an incomplete dependency closure. Every other bare
  // import resolves upward from packages/vue to real node_modules.
  writeFileSync(
    join(scratchDir, "src", "consumer-provided.d.ts"),
    [
      "// Generated by test-registry-local.mjs",
      'declare module "@chelone/vue";',
      'declare module "@chelone/core";',
      'declare module "@chelone/core/*";',
      "",
    ].join("\n"),
  );

  writeFileSync(
    join(scratchDir, "tsconfig.json"),
    `${JSON.stringify(
      {
        compilerOptions: {
          target: "ES2022",
          lib: ["ES2022", "DOM", "DOM.Iterable"],
          module: "ESNext",
          moduleResolution: "bundler",
          jsx: "preserve",
          strict: true,
          verbatimModuleSyntax: true,
          noUncheckedIndexedAccess: true,
          // Only resolution is gated, so pre-existing implicit any in the
          // copied source must not mask a resolution failure.
          noImplicitAny: false,
          noEmit: true,
          skipLibCheck: true,
          esModuleInterop: true,
          isolatedModules: true,
          moduleDetection: "force",
          baseUrl: ".",
          paths: { "@/*": ["./src/*"] },
          types: [],
          rootDir: "src",
        },
        include: ["src"],
      },
      null,
      2,
    )}\n`,
  );

  // Without its own package.json, `@chelone/vue` would self-reference through
  // packages/vue/package.json to the real src/ and bypass the stub above.
  writeFileSync(
    join(scratchDir, "package.json"),
    `${JSON.stringify({ name: "chelone-vue-local-consumer", private: true, type: "module" }, null, 2)}\n`,
  );

  const files = [...writtenPaths].sort();
  console.log(
    `Local linked-consumer check: ${items.size} items, ${files.length} files copied into ${scratchDir}`,
  );

  let compilerOutput = "";
  let run = { status: 0 };
  try {
    compilerOutput = execFileSync(
      join(pkgRoot, "node_modules", ".bin", "vue-tsc"),
      ["--noEmit", "--project", "tsconfig.json"],
      { cwd: scratchDir, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    );
  } catch (err) {
    compilerOutput = `${err.stdout ?? ""}${err.stderr ?? ""}`;
    run = { code: err.code, status: err.status };
  }

  const crash = compilerRunFailure({ ...run, output: compilerOutput });
  if (crash) {
    console.error(
      `\nLocal linked-consumer check FAILED: ${crash}\nScratch left at ${scratchDir} for inspection.`,
    );
    process.exit(1);
  }

  const resolutionErrors = filterResolutionErrors(compilerOutput);
  if (resolutionErrors.length > 0) {
    console.error(
      `\nLocal linked-consumer check FAILED: ${resolutionErrors.length} unresolved import(s) in copied files. Scratch left at ${scratchDir} for inspection:\n${resolutionErrors.map((l) => `  ${l}`).join("\n")}`,
    );
    process.exit(1);
  }

  rmSync(scratchDir, { recursive: true, force: true });
  console.log(
    `Local linked-consumer check PASSED: ${files.length} copied files across ${items.size} items resolve every import.`,
  );
};

// import.meta.url is built from the real path of the main module, while
// process.argv[1] is not resolved, so a symlinked checkout needs realpath.
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href
) {
  main();
}

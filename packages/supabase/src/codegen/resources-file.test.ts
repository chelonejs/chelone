import { describe, expect, it } from "vitest";
import type { DatabaseRelation } from "./database-relations";
import {
  generateResourceScaffold,
  generateResourcesFile,
  supazodRowSchemaName,
} from "./resources-file";

const table = (
  name: string,
  references: DatabaseRelation["references"] = [],
): DatabaseRelation => ({ name, kind: "table", references });

const view = (
  name: string,
  references: DatabaseRelation["references"] = [],
): DatabaseRelation => ({ name, kind: "view", references });

/** What supazod writes: one `export const` per Row schema. */
const schemasText = (names: string[]) =>
  names.map((name) => `export const ${name} = z.object({});`).join("\n");

describe("supazodRowSchemaName", () => {
  it("matches supazod 4.5.0 names for snake case, single word and mixed case tables", () => {
    expect(supazodRowSchemaName("public", "blog_posts")).toBe(
      "publicBlogPostsRowSchema",
    );
    expect(supazodRowSchemaName("public", "posts")).toBe(
      "publicPostsRowSchema",
    );
    expect(supazodRowSchemaName("public", "BlogPosts")).toBe(
      "publicBlogPostsRowSchema",
    );
    expect(supazodRowSchemaName("my_schema", "order_items")).toBe(
      "mySchemaOrderItemsRowSchema",
    );
  });
});

describe("generateResourcesFile", () => {
  const generate = (
    relations: DatabaseRelation[],
    schemaNames = relations.map(({ name }) =>
      supazodRowSchemaName("public", name),
    ),
  ) =>
    generateResourcesFile({
      relations,
      schema: "public",
      schemasFile: schemasText(schemaNames),
      schemasImport: "./schemas",
    });

  it("writes defineResources with one entry per relation, sorted by name", () => {
    expect(
      generate([table("posts"), view("authors_view"), table("authors")]),
    ).toBe(`// Written by \`chelone-supabase gen\`. Do not edit this file; run the command again instead.
import { defineResources } from "@chelone/core";
import {
  publicAuthorsRowSchema,
  publicAuthorsViewRowSchema,
  publicPostsRowSchema,
} from "./schemas";

export const resources = defineResources({
  authors: { schema: publicAuthorsRowSchema },
  authors_view: { schema: publicAuthorsViewRowSchema },
  posts: { schema: publicPostsRowSchema },
});

declare module "@chelone/core" {
  interface Register {
    resources: typeof resources;
  }
}
`);
  });

  it("adds references to relations in the map and leaves out the others", () => {
    const text = generate([
      table("posts", [
        { column: "author_id", relation: "authors" },
        { column: "owner_id", relation: "users" },
      ]),
      table("authors", [{ column: "user_id", relation: "users" }]),
    ]);
    expect(text).toContain(
      '  posts: {\n    schema: publicPostsRowSchema,\n    references: { author_id: "authors" },\n  },',
    );
    expect(text).toContain("  authors: { schema: publicAuthorsRowSchema },");
    expect(text).not.toContain("users");
    expect(text).not.toContain("owner_id");
  });

  it("quotes a key that is not an identifier", () => {
    const text = generate([
      table("blog-comments", [{ column: "post-id", relation: "blog-posts" }]),
      table("blog-posts"),
    ]);
    expect(text).toContain('"blog-comments": {');
    expect(text).toContain('references: { "post-id": "blog-posts" }');
    expect(text).toContain(
      '"blog-posts": { schema: publicBlogPostsRowSchema }',
    );
  });

  it("ends with the Register augmentation", () => {
    expect(generate([table("posts")])).toMatch(
      /declare module "@chelone\/core" \{\n {2}interface Register \{\n {4}resources: typeof resources;\n {2}\}\n\}\n$/,
    );
  });

  it("throws naming a relation whose schema supazod did not export", () => {
    expect(() =>
      generateResourcesFile({
        relations: [table("posts"), table("authors")],
        schema: "public",
        schemasFile: schemasText(["publicPostsRowSchema"]),
        schemasImport: "./schemas",
      }),
    ).toThrow(/authors.*publicAuthorsRowSchema/);
  });

  it("throws naming two relations with the same schema name", () => {
    expect(() =>
      generate(
        [table("blog_posts"), table("BlogPosts")],
        ["publicBlogPostsRowSchema"],
      ),
    ).toThrow(/blog_posts.*BlogPosts|BlogPosts.*blog_posts/);
  });
});

describe("generateResourceScaffold", () => {
  const relations = [table("posts"), view("published_posts")];

  it("gives a table list, edit and show and a view list and show, for React and Vue", () => {
    expect(generateResourceScaffold(relations, "react")).toBe(
      `<Resource
  name="posts"
  list={ListGuesser}
  edit={EditGuesser}
  show={ShowGuesser}
/>
<Resource
  name="published_posts"
  list={ListGuesser}
  show={ShowGuesser}
/>
`,
    );
    expect(generateResourceScaffold(relations, "vue")).toBe(
      `<Resource
  name="posts"
  :list="ListGuesser"
  :edit="EditGuesser"
  :show="ShowGuesser"
/>
<Resource
  name="published_posts"
  :list="ListGuesser"
  :show="ShowGuesser"
/>
`,
    );
  });
});

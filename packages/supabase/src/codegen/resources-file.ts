import type { DatabaseRelation } from "./database-relations";

const words = (text: string): string[] =>
  text
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter((word) => word !== "");

const capitalize = (word: string) =>
  word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();

const upperFirst = (word: string) =>
  word.charAt(0).toUpperCase() + word.slice(1);

const camelCase = (text: string): string =>
  words(text)
    .map((word, index) => (index === 0 ? word.toLowerCase() : capitalize(word)))
    .join("");

/**
 * The name supazod 4.5.0 gives a relation's Row schema by default:
 * `{schema}{table}Row` with each part camel-cased, then `Schema`.
 */
export function supazodRowSchemaName(schema: string, relation: string): string {
  return `${camelCase(schema)}${upperFirst(camelCase(relation))}RowSchema`;
}

export interface ResourcesFileInput {
  relations: DatabaseRelation[];
  schema: string;
  /** The text of the module supazod wrote, to check each Row schema is exported. */
  schemasFile: string;
  /** The module specifier the resources file imports the schemas from. */
  schemasImport?: string;
}

const exportedConstNames = (text: string): Set<string> => {
  const names = new Set<string>();
  for (const match of text.matchAll(/^export\s+const\s+([A-Za-z_$][\w$]*)/gm)) {
    const [, name] = match;
    if (name !== undefined) names.add(name);
  }
  return names;
};

const isIdentifier = (key: string) => /^[A-Za-z_$][\w$]*$/.test(key);

const propertyKey = (key: string) =>
  isIdentifier(key) ? key : JSON.stringify(key);

const compare = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

const header =
  "// Written by `chelone-supabase gen`. Do not edit this file; run the command again instead.";

const registerAugmentation = `declare module "@chelone/core" {
  interface Register {
    resources: typeof resources;
  }
}
`;

/** The text of a resources file: a `defineResources` map of each relation's Row schema, and the `Register` augmentation. */
export function generateResourcesFile({
  relations,
  schema,
  schemasFile,
  schemasImport = "./schemas",
}: ResourcesFileInput): string {
  const sorted = [...relations].sort((a, b) => compare(a.name, b.name));
  const schemaNames = new Map<string, string>();
  const exported = exportedConstNames(schemasFile);
  for (const { name } of sorted) {
    const schemaName = supazodRowSchemaName(schema, name);
    for (const [other, otherSchemaName] of schemaNames) {
      if (otherSchemaName === schemaName) {
        throw new Error(
          `The relations "${other}" and "${name}" both get the schema name ${schemaName}.`,
        );
      }
    }
    schemaNames.set(name, schemaName);
  }
  for (const [name, schemaName] of schemaNames) {
    if (!exported.has(schemaName)) {
      throw new Error(
        `The relation "${name}" needs \`export const ${schemaName}\` in the schemas file, and supazod did not write it.`,
      );
    }
  }

  const entries = sorted.map(({ name, references }) => {
    const schemaName = schemaNames.get(name);
    // An object literal cannot repeat a key, so the first foreign key on a column wins.
    const kept = references.filter(
      ({ column, relation }, index) =>
        schemaNames.has(relation) &&
        references.findIndex(
          (other) => other.column === column && schemaNames.has(other.relation),
        ) === index,
    );
    if (kept.length === 0) {
      return `  ${propertyKey(name)}: { schema: ${schemaName} },`;
    }
    const pairs = kept
      .map(
        ({ column, relation }) =>
          `${propertyKey(column)}: ${JSON.stringify(relation)}`,
      )
      .join(", ");
    return `  ${propertyKey(name)}: {\n    schema: ${schemaName},\n    references: { ${pairs} },\n  },`;
  });

  const imports = [...schemaNames.values()]
    .sort(compare)
    .map((schemaName) => `  ${schemaName},`)
    .join("\n");

  return `${header}
import { defineResources } from "@chelone/core";
import {
${imports}
} from ${JSON.stringify(schemasImport)};

export const resources = defineResources({
${entries.join("\n")}
});

${registerAugmentation}`;
}

const guesserProps = {
  react: (prop: string, guesser: string) => `${prop}={${guesser}}`,
  vue: (prop: string, guesser: string) => `:${prop}="${guesser}"`,
};

/** `<Resource>` elements that put a guesser on each page: a table gets list, edit and show, a view list and show. */
export function generateResourceScaffold(
  relations: DatabaseRelation[],
  adapter: "react" | "vue",
): string {
  const prop = guesserProps[adapter];
  return relations
    .map(({ name, kind }) => {
      const props = [
        prop("list", "ListGuesser"),
        ...(kind === "table" ? [prop("edit", "EditGuesser")] : []),
        prop("show", "ShowGuesser"),
      ];
      return `<Resource\n  name=${JSON.stringify(name)}\n${props.map((line) => `  ${line}`).join("\n")}\n/>\n`;
    })
    .join("");
}
